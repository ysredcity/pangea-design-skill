#!/usr/bin/env node
/**
 * sync-from-skill.mjs —— 单向同步：skill → website
 * ------------------------------------------------------------------
 * 官网是 skill 的 showcase（dogfood），但保持工程独立、可单独部署。
 * 本脚本把 skill 的产物**快照**进 website/src/generated/，官网只消费快照，
 * 运行时不 import skills/** 内部路径。skill 是唯一事实源；skill 变更后重跑本脚本。
 *
 * 同步项：
 *   - references/_generated/catalog.json            → src/generated/catalog.json（元数据）
 *   - CHANGELOG.md                                  → src/generated/CHANGELOG.md（更新日志页）
 *   - templates/project-starter/src/components/LazyChart.vue
 *                                                   → src/generated/templates/components/LazyChart.vue
 *   - templates/project-starter/src/pages/{示例页}  → src/generated/templates/pages/{示例页}
 *     （Dashboard 的 `@/components/LazyChart.vue` 导入改写为相对路径，指向同步过来的 LazyChart）
 *   - templates/project-starter/src/components/{产品}  → src/generated/business/{产品}
 *     （产品专属业务组件，如 msc/MscAttachmentUpload.vue；官网「MSC 组件」模块的预览页直接 import 快照）
 *
 * 运行：node scripts/sync-from-skill.mjs   （在 website/ 下）
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(HERE, '..', '..');
const SKILL_DIR = join(REPO_ROOT, 'skills', 'pangea-design-vue');
const STARTER = join(SKILL_DIR, 'templates', 'project-starter');
const GEN_DIR = join(HERE, '..', 'src', 'generated');
const TPL_DIR = join(GEN_DIR, 'templates');
const BIZ_DIR = join(GEN_DIR, 'business');

const AUTO_NOTE = 'AUTO-GENERATED by website/scripts/sync-from-skill.mjs — 请勿手改。改内容请改 skill 内源文件后重跑同步。';

// 需要作为「页面模板预览」同步的示例页目录
const EXAMPLE_PAGES = [
  'Example',
  'CardList',
  'TreeTable',
  'ContractForm',
  'GroupedForm',
  'StepForm',
  'DetailPage',
  'ApprovalDetail',
  'Dashboard',
];

// 产品专属业务组件的产品目录（skill 侧 src/components/<产品>/）
const BUSINESS_PRODUCTS = ['msc'];

if (!existsSync(GEN_DIR)) mkdirSync(GEN_DIR, { recursive: true });

/** 递归复制目录（可选内容转换） */
function copyDir(src, dest, transform) {
  mkdirSync(dest, { recursive: true });
  for (const e of readdirSync(src, { withFileTypes: true })) {
    const s = join(src, e.name);
    const d = join(dest, e.name);
    if (e.isDirectory()) copyDir(s, d, transform);
    else {
      let content = readFileSync(s, 'utf8');
      if (transform) content = transform(s, content);
      writeFileSync(d, content, 'utf8');
    }
  }
}

let ok = 0;
const log = (msg) => {
  ok++;
  console.log('✓ ' + msg);
};

// 1) catalog.json（+ _note）
{
  const src = join(SKILL_DIR, 'references', '_generated', 'catalog.json');
  if (!existsSync(src)) {
    console.error(`✗ 缺少 ${src}\n  请先在 skill 目录运行 node scripts/build-catalog.mjs 生成。`);
    process.exitCode = 1;
  } else {
    const json = JSON.parse(readFileSync(src, 'utf8'));
    json._note = AUTO_NOTE;
    writeFileSync(join(GEN_DIR, 'catalog.json'), JSON.stringify(json, null, 2) + '\n', 'utf8');
    log('catalog.json');
  }
}

// 2) CHANGELOG.md（更新日志页数据源，verbatim）
{
  const src = join(REPO_ROOT, 'CHANGELOG.md');
  if (existsSync(src)) {
    writeFileSync(join(GEN_DIR, 'CHANGELOG.md'), readFileSync(src, 'utf8'), 'utf8');
    log('CHANGELOG.md');
  } else {
    console.error(`✗ 缺少 ${src}`);
    process.exitCode = 1;
  }
}

// 3) LazyChart.vue → templates/components/
{
  const src = join(STARTER, 'src', 'components', 'LazyChart.vue');
  if (existsSync(src)) {
    mkdirSync(join(TPL_DIR, 'components'), { recursive: true });
    writeFileSync(join(TPL_DIR, 'components', 'LazyChart.vue'), readFileSync(src, 'utf8'), 'utf8');
    log('templates/components/LazyChart.vue');
  }
}

// 4) 示例页 → templates/pages/（Dashboard 改写 LazyChart 导入为相对路径）
for (const name of EXAMPLE_PAGES) {
  const src = join(STARTER, 'src', 'pages', name);
  if (!existsSync(src)) {
    console.error(`✗ 缺少示例页目录 ${src}`);
    process.exitCode = 1;
    continue;
  }
  copyDir(src, join(TPL_DIR, 'pages', name), (path, content) => {
    // Dashboard 用 '@/components/LazyChart.vue'；website 里 LazyChart 在 generated/templates/components/
    if (path.replace(/\\/g, '/').includes('/Dashboard/')) {
      return content.replace(
        "@/components/LazyChart.vue",
        "../../components/LazyChart.vue"
      );
    }
    return content;
  });
  log(`templates/pages/${name}`);
}

// 5) 产品专属业务组件 → business/<产品>/
for (const product of BUSINESS_PRODUCTS) {
  const src = join(STARTER, 'src', 'components', product);
  if (!existsSync(src)) {
    console.error(`✗ 缺少业务组件目录 ${src}`);
    process.exitCode = 1;
    continue;
  }
  copyDir(src, join(BIZ_DIR, product));
  log(`business/${product}`);
}

// 生成目录说明
writeFileSync(
  join(GEN_DIR, 'README.md'),
  `# src/generated（自动生成，勿手改）\n\n${AUTO_NOTE}\n\n由 \`npm run sync\`（\`scripts/sync-from-skill.mjs\`）从 skill 单向同步。这些快照会**提交进 git**，使官网可独立构建/部署，无需构建时访问 skill。\n\n包含：\n- \`catalog.json\` — 页面模板/组件/业务组件选型元数据\n- \`CHANGELOG.md\` — 更新日志页数据源\n- \`templates/\` — 页面模板预览用的示例页 + LazyChart（Dashboard 的 LazyChart 导入已改为相对路径）\n- \`business/\` — 产品专属业务组件（按产品分目录，如 \`msc/\`），供官网对应模块的预览页 import\n`,
  'utf8'
);

console.log(`同步完成：${ok} 项。`);
